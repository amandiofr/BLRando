<#
.SYNOPSIS
  Installs the BL family launcher icon into an Android project.

.DESCRIPTION
  Three layers:
    1. background : diagonal gradient, colors given here (-Dark / -Light)
    2. arrows     : the shared outward arrows (layers\bl_icon_arrows.xml, always overwritten)
    3. center     : the app's own drawing (res\drawable\bl_icon_center.xml, created from the
                    template only if missing, never overwritten)

  Files written in <Project>\app\src\main\res :
    drawable\bl_icon_arrows.xml, drawable\ic_launcher_bg.xml, drawable\ic_launcher_fg.xml,
    mipmap-anydpi-v26\ic_launcher.xml, values\bl_icon_colors.xml
    (+ drawable\bl_icon_center.xml from the template if absent)

  The kit lives in <project>\iconkit (one copy per BL project, no shared folder).
  -Project defaults to the project containing this iconkit folder.

.EXAMPLE
  .\iconkit\New-BLIcon.ps1 -Dark "#0B3D12" -Light "#43A047"
#>
param(
    [string] $Project = (Split-Path $PSScriptRoot),
    [Parameter(Mandatory)] [string] $Dark,
    [Parameter(Mandatory)] [string] $Light,
    [int] $Angle = 45
)
$ErrorActionPreference = 'Stop'
$kit = $PSScriptRoot
$res = Join-Path $Project 'app\src\main\res'
if (-not (Test-Path $res)) { throw "Not an Android project (missing $res)" }
foreach ($c in $Dark, $Light) {
    if ($c -notmatch '^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$') { throw "Bad color '$c' (expected #RRGGBB or #AARRGGBB)" }
}

$utf8 = New-Object System.Text.UTF8Encoding($false)
function Write-Res([string] $rel, [string] $text) {
    $path = Join-Path $res $rel
    New-Item -ItemType Directory -Force (Split-Path $path) | Out-Null
    [IO.File]::WriteAllText($path, $text.Replace("`r`n", "`n"), $utf8)
    Write-Host "  wrote $rel"
}

# Refuse to create duplicate color resources
$dupes = Get-ChildItem (Join-Path $res 'values*') -Filter *.xml -Recurse |
    Where-Object { $_.Name -ne 'bl_icon_colors.xml' } |
    Select-String -Pattern 'name="bl_icon_(dark|light)"' -List
if ($dupes) { throw "bl_icon_dark/bl_icon_light already defined in: $($dupes.Path -join ', '). Remove them first." }

Write-Host "BL icon -> $Project"

Copy-Item (Join-Path $kit 'layers\bl_icon_arrows.xml') (Join-Path $res 'drawable\bl_icon_arrows.xml') -Force
Write-Host "  wrote drawable\bl_icon_arrows.xml"

$center = Join-Path $res 'drawable\bl_icon_center.xml'
if (Test-Path $center) { Write-Host "  kept  drawable\bl_icon_center.xml" }
else {
    Copy-Item (Join-Path $kit 'templates\bl_icon_center.xml') $center
    Write-Host "  wrote drawable\bl_icon_center.xml (placeholder: draw your app's subject in it)"
}

Write-Res 'values\bl_icon_colors.xml' @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by iconkit\New-BLIcon.ps1 -->
<resources>
    <color name="bl_icon_dark">$Dark</color>
    <color name="bl_icon_light">$Light</color>
</resources>
"@

Write-Res 'drawable\ic_launcher_bg.xml' @"
<?xml version="1.0" encoding="utf-8"?>
<!-- BL family, layer 1. Generated by iconkit\New-BLIcon.ps1: change the colors with the script. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient
        android:angle="$Angle"
        android:endColor="@color/bl_icon_light"
        android:startColor="@color/bl_icon_dark"
        android:type="linear" />
</shape>
"@

Write-Res 'drawable\ic_launcher_fg.xml' @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by iconkit\New-BLIcon.ps1. Shared arrows + app center: edit bl_icon_center.xml, not this file. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/bl_icon_arrows" />
    <item android:drawable="@drawable/bl_icon_center" />
</layer-list>
"@

Write-Res 'mipmap-anydpi-v26\ic_launcher.xml' @"
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_bg" />
    <foreground android:drawable="@drawable/ic_launcher_fg" />
</adaptive-icon>
"@

Write-Host "Done. Manifest must use android:icon=`"@mipmap/ic_launcher`"."
